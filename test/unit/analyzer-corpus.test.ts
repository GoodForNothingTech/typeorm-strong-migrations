/**
 * The acceptance target: everything `typeorm migration:generate` emits must parse.
 *
 * These are the rendered forms of the template literals in
 * `PostgresQueryRunner.ts` and `MysqlQueryRunner.ts`, quirks included — the double
 * space and trailing space in `createIndexSql`, `ADD` without `COLUMN` on Postgres,
 * `CHANGE` rather than `MODIFY` on MySQL, `numeric(12,7) array`, and the
 * semicolon-joined `CREATE TABLE` + `COMMENT ON COLUMN` that arrives as a single
 * `query()` call.
 *
 * A single `kind: "unknown"` here means a real-world generated migration would go
 * unchecked, so that is what the sweep asserts.
 */

